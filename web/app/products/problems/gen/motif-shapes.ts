/* =========================================================================
   模写（絵柄）モチーフ・ライブラリ（pack-design §11.1 絵柄1シリーズ）
   ランダムウォークでは「絵」にならないため、絵柄は手設計の原型（モチーフ）
   ＋累積ディテールのライブラリ方式で自動設計する。
   - paths: "c,r c,r …" のポリライン（r は下向き）。連続ペアが辺になる
   - details: 累積適用（prefix のみ）。とびら→まど→えんとつ のように
     足すほど線が増え、metrics 経由で自然に上位 Lv 帯へ移る
   - mirrorable: 左右反転を別候補として出してよい（非対称形のみ）
   座標はモチーフローカル。配置（盤面内の平行移動）はジェネレータが行う。
   ========================================================================= */

import type { EdgeT, Pt } from "../schema";

export type MotifDetail = { name: string; paths: string[] };

export type MotifDef = {
  key: string;        // 変種キーの基底（一意）
  name: string;       // 検品ラベル（ひらがな）
  paths: string[];    // 基本形
  details?: MotifDetail[];
  mirrorable?: boolean;
};

/* "0,1 2,1 2,2" → [[0,1]-[2,1], [2,1]-[2,2]] */
export function parsePaths(paths: string[]): EdgeT[] {
  const out: EdgeT[] = [];
  for (const path of paths) {
    const pts: Pt[] = path.trim().split(/\s+/).map((tok) => {
      const [c, r] = tok.split(",").map(Number);
      if (!Number.isInteger(c) || !Number.isInteger(r)) {
        throw new Error(`motif path の座標が不正: "${tok}" in "${path}"`);
      }
      return [c, r] as Pt;
    });
    for (let i = 0; i + 1 < pts.length; i++) out.push([pts[i], pts[i + 1]]);
  }
  return out;
}

